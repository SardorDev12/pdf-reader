// Bundles PDF.js (3.x, classic scripts) + our viewer into one self-contained HTML string.
//   npm run build:pdf            -> regenerates src/reader/pdf/viewerAssets.ts
//   node scripts/build-pdf-viewer.mjs --html out.html   (also writes the raw HTML, for browser testing)
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(root, p), 'utf8');
// keep embedded code from terminating the surrounding <script> element
const safe = (code) => code.replace(/<\/script/gi, '<\\/script');

const css = read('src/reader/pdf/viewer.css');
const viewer = read('src/reader/pdf/viewer.js');
const pdfMain = read('node_modules/pdfjs-dist/build/pdf.min.js');
const pdfWorker = read('node_modules/pdfjs-dist/build/pdf.worker.min.js');

const html = [
  '<!doctype html><html><head><meta charset="utf-8">',
  '<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no">',
  `<style>${css}</style></head><body><div id="viewer"></div>`,
  `<script>window.__PM_WORKER__ = ${safe(JSON.stringify(pdfWorker))};</script>`,
  `<script>${safe(pdfMain)}</script>`,
  `<script>${safe(viewer)}</script>`,
  '</body></html>',
].join('\n');

const version = createHash('sha1').update(html).digest('hex').slice(0, 10);

writeFileSync(
  join(root, 'src/reader/pdf/viewerAssets.ts'),
  `// AUTO-GENERATED by scripts/build-pdf-viewer.mjs - do not edit. Run \`npm run build:pdf\`.\n` +
    `export const PDF_VIEWER_VERSION = ${JSON.stringify(version)};\n` +
    `export const PDF_VIEWER_HTML = ${JSON.stringify(html)};\n`,
);

const out = process.argv.indexOf('--html');
if (out > -1) writeFileSync(process.argv[out + 1], html);
console.log(`viewer ${version}: ${(html.length / 1024).toFixed(0)} KB`);
